export const cleanupBrokenVideos = async (req, res) => {
  try {
    const allVideos = await video.find();
    console.log("Total videos scanned:", allVideos.length);
    const results = await Promise.all(
      allVideos.map(async (doc) => ({
        doc,
        playable: await isPlayableVideoAsync(doc),
      }))
    );

    const brokenVideos = results.filter((item) => !item.playable).map((item) => item.doc);
    console.log("Broken videos detected:", brokenVideos.length);
    brokenVideos.forEach((doc) => console.log("Broken video detected:", doc._id));

    await Promise.all(
      brokenVideos.map((doc) =>
        cleanupVideoAssets(doc).catch((error) => {
          console.warn(
            `Failed to cleanup assets for broken video ${doc._id}:`,
            error && error.message ? error.message : error
          );
        })
      )
    );

    const brokenIds = brokenVideos.map((doc) => doc._id);
    const deleteResult = brokenIds.length
      ? await video.deleteMany({ _id: { $in: brokenIds } })
      : { deletedCount: 0 };
    const deletedCount = deleteResult.deletedCount || 0;
    const remainingCount = Math.max(0, allVideos.length - deletedCount);

    console.log("Deleted broken videos:", deletedCount);
    console.log("Remaining videos:", remainingCount);

    return res.status(200).json({
      success: true,
      removed: deletedCount,
      remaining: remainingCount,
    });
  } catch (error) {
    console.error("Cleanup broken videos error:", error);
    return res.status(500).json({ message: "Something went wrong" });
  }
};

export async function generateMissingThumbnails() {
  try {
    const videosWithoutThumbnail = await video.find({
      customThumbnailUrl: { $in: [null, undefined, ""] },
      autoGeneratedThumbnailUrl: { $in: [null, undefined, ""] },
      thumbnail: { $in: [null, undefined, ""] },
    });

    for (const doc of videosWithoutThumbnail) {
      try {
        if (!doc.filepath) continue;
        // If filepath is a remote URL (Cloudinary), skip disk-based thumbnail generation
        if (typeof doc.filepath === 'string' && /^(https?:)?\/\//i.test(doc.filepath)) {
          console.log(`Skipping thumbnail generation for remote filepath for video ${doc._id}`);
          continue;
        }
        const autoGeneratedThumbnailUrl = await generateAutoThumbnail(resolveDiskPath(doc.filepath));
        doc.autoGeneratedThumbnailUrl = autoGeneratedThumbnailUrl;
        doc.thumbnail = autoGeneratedThumbnailUrl;
        await doc.save();
      } catch (error) {
        console.error(`Failed to generate thumbnail for video ${doc._id}:`, error.message || error);
      }
    }
  } catch (error) {
    console.error("Missing thumbnail generation failed:", error);
  }
}
